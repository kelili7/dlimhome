import { test, expect } from '@playwright/test'
import { openPage } from './helpers/navigation.js'

test('support contact guidance lives in the bilingual FAQ and preserves the enquiry link', async ({ page }) => {
  await openPage(page, '/support#faq')
  await expect(page.locator('#faq-heading')).toHaveText('Frequently Asked Questions')
  await expect(page.locator('.cta-panel')).toHaveCount(0)
  const questions = page.locator('.faq-trigger')
  await expect(questions).toHaveCount(6)
  await questions.first().focus()
  await page.keyboard.press('End')
  await expect(questions.last()).toBeFocused()
  await page.keyboard.press('Enter')
  const panel = page.locator('#faq-panel-5')
  await expect(questions.last()).toHaveAttribute('aria-expanded', 'true')
  await expect(panel).not.toHaveAttribute('inert', '')
  await expect(panel).toContainText('For an existing order, contact us through the store you purchased from.')
  const contactLink = panel.getByRole('link')
  await expect(contactLink).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(contactLink).toBeFocused()
  await expect(contactLink).toHaveAttribute('href', '/contact/business-enquiry')

  await page.getByRole('button', { name: 'Switch to Chinese' }).click()
  await expect(page.locator('#faq-heading')).toHaveText('常见问题解答')
  await expect(questions.last()).toHaveText('还有其他问题？')
  await expect(panel).toContainText('已购订单请通过购买店铺联系客服。新产品咨询或商业合作，可以在这里整理您的需求。')
  await expect(contactLink).toHaveText('与我们聊聊')
  await questions.first().click()
  await expect(questions.last()).toHaveAttribute('aria-expanded', 'false')
  await expect(panel).toHaveAttribute('inert', '')
  await questions.last().click()
  await contactLink.click()
  await expect(page).toHaveURL('/contact/business-enquiry')
})
